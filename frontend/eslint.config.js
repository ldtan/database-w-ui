// Narrow on purpose, for the reason the backend's ruff config spells out at length:
// a gate that starts dozens of findings in the red is not a gate, it is a thing
// people learn to skip. `tsconfig.json` already carries `noUnusedLocals`,
// `noUnusedParameters` and `noFallthroughCasesInSwitch`, so typechecking does much of
// what a default config would — what it cannot see is React's rules, and those are
// the ones that produce the bugs this app has actually had.
//
// `react-hooks/exhaustive-deps` is the one that earns its place, and it is a
// **warning**. Three separate data-loss bugs here were dependency arrays: the view
// config re-seeding on `views.data` identity and wiping an unsaved filter, the forms
// editor re-seeding on the `columns` prop, and the export dialog re-ticking every
// column. All three are exactly what this rule points at. It stays a warning because
// the codebase also has deliberate suppressions with comments explaining them
// (LocationField's map effect must not rebuild the map; ReferencePicker's memo cannot
// list `labelFor`) — an error would mean weakening those or failing the build over
// them.
import js from "@eslint/js";
import globals from "globals";
import tseslint from "typescript-eslint";
import reactHooks from "eslint-plugin-react-hooks";

export default tseslint.config(
  {
    // `api-schema.ts` is generated by `npm run gen:api`; linting it would mean
    // findings nobody can fix without editing the generator's output.
    ignores: ["dist/**", "node_modules/**", "src/lib/api-schema.ts"],
  },
  js.configs.recommended,
  ...tseslint.configs.recommended,

  {
    files: ["src/**/*.{ts,tsx}"],
    plugins: { "react-hooks": reactHooks },
    rules: {
      ...reactHooks.configs.recommended.rules,
      "react-hooks/exhaustive-deps": "warn",

      // The three React Compiler-era rules that this codebase deliberately and
      // repeatedly does not satisfy. Each is a real recommendation and each is
      // documented here where it is broken, so an error would just mean 42
      // suppression comments:
      //
      // - `set-state-in-effect` (31): seeding local state from props in an effect is
      //   how every dialog in this app opens on a record.
      // - `refs` (8): `const xRef = useRef(x); xRef.current = x;` during render is
      //   the established idiom for reading a fresh value inside a callback whose
      //   effect must not re-run — LocationField's map and ReferencePicker's search
      //   both depend on it, with comments saying why.
      // - `use-memo` (3).
      //
      // Turning these on is a piece of work with its own diff, not a thing to do
      // while fixing something else.
      "react-hooks/set-state-in-effect": "off",
      "react-hooks/refs": "off",
      "react-hooks/use-memo": "off",

      // Reported by the typechecker already, with better information. Two reporters
      // for one finding is noise.
      "@typescript-eslint/no-unused-vars": "off",

      // `any` appears where this app meets untyped JSON — a column's `config` and a
      // record's `data` are `dict` to Pydantic, so OpenAPI says "object" and the
      // frontend's types are its own claim about them (see known-gaps). Banning it
      // would mean either lying about those shapes or suppressing per line.
      "@typescript-eslint/no-explicit-any": "off",

      // Flags the dead initialiser in `let hours = 0; let minutes = 0; let seconds
      // = 0;` where every branch below destructures into them. The symmetry is the
      // readable form and dropping one initialiser to satisfy this would be worse.
      "no-useless-assignment": "off",
    },
  },

  {
    // `phone.test.ts` asserts that exotic whitespace does *not* survive cleaning,
    // which means writing a character class full of exotic whitespace. Flagging it
    // is the rule doing its job on a file where the irregular characters are the
    // subject rather than a typo.
    files: ["src/**/*.test.ts"],
    rules: { "no-irregular-whitespace": ["error", { skipRegExps: true }] },
  },

  {
    // A Node script, not browser code — it drives Playwright and reads `process`.
    // Without this, `globals.browser`-less config reports every Node builtin as
    // undefined, which was 25 of the first run's 69 errors and none of them real.
    files: ["scripts/**/*.mjs"],
    languageOptions: { globals: { ...globals.node, ...globals.browser } },
  },
);
